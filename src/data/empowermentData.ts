export const getTierByPoints = (points: number): EmpowermentTier => {
  for (let i = EMPOWERMENT_TIERS.length - 1; i >= 0; i--) {
    if (points >= EMPOWERMENT_TIERS[i].minPoints) {
      return EMPOWERMENT_TIERS[i];
    }
  }
  return EMPOWERMENT_TIERS[0];
};

export const getNextTier = (points: number): EmpowermentTier | null => {
  const currentTier = getTierByPoints(points);
  const next = EMPOWERMENT_TIERS.find((t) => t.level === currentTier.level + 1);
  return next || null;
};
